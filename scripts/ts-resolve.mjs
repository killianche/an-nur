/**
 * Точка регистрации резолвера для запуска модулей проекта в Node.
 *
 * Проект пишет импорты без расширения (`./reciters`), как принято в
 * бандлерах.  Node так не умеет: `--experimental-strip-types` читает
 * .ts-файлы, но путь ему нужен точный.  Хук в ts-resolve-hooks.mjs
 * дописывает `.ts` (а для папок — `/index.ts`), когда обычное
 * разрешение не сработало.
 *
 * Зачем: без него тестами покрывались только модули без импортов.
 * С ним в Node открывается весь src — например поиск по переводу,
 * который тянет за собой quran-sources на 3.7 МБ.
 *
 * Подключается флагом `--import ./scripts/ts-resolve.mjs`.
 * Только для тестов: сборкой занимается Vite, его это не касается.
 */
import { register } from 'node:module';

