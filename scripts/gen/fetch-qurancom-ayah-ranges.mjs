#!/usr/bin/env node
/**
 * Fetch ayah boundaries inside Quran.com full-surah recitations.
 *
 * These ranges let online playback keep one HTMLAudioElement running while
 * the UI advances from ayah to ayah. The natural pause in the recording stays,
 * but there is no file/network/decoder handoff at each boundary.
 *
 * Run: node scripts/gen/fetch-qurancom-ayah-ranges.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '../..');
const OUT = resolve(ROOT, 'src/content/qurancom-ayah-ranges.ts');
const API = 'https://api.qurancdn.com/api/qdc/audio/reciters';
const RECITERS = { alafasy: 7, shaatree: 4, yasser: 97, ajmi: 19 };
const COUNTS = [
  7,286,200,176,120,165,206,75,129,109,123,111,43,52,99,128,111,110,98,135,
  112,78,118,64,77,227,93,88,69,60,34,30,73,54,45,83,182,88,75,85,54,53,89,
  59,37,35,38,29,18,45,60,49,62,55,78,96,29,22,24,13,14,11,11,18,12,12,30,
  52,52,44,28,28,20,56,40,31,50,40,46,42,29,19,36,25,22,17,19,26,30,20,15,
  21,11,8,8,19,5,8,8,11,11,8,3,9,5,4,7,3,6,3,5,4,5,6,
];

async function fetchRanges(apiId, reciter, surah) {
  const url = `${API}/${apiId}/audio_files?chapter=${surah}&segments=true`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${reciter} ${surah}: HTTP ${response.status}`);
  const data = await response.json();
  const timings = data.audio_files?.[0]?.verse_timings;
  if (!Array.isArray(timings) || timings.length !== COUNTS[surah - 1]) {
    throw new Error(`${reciter} ${surah}: invalid ayah count`);
  }
  return timings.map((item, index) => {
    const expectedKey = `${surah}:${index + 1}`;
    if (item.verse_key !== expectedKey || !Number.isInteger(item.timestamp_from)
      || !Number.isInteger(item.timestamp_to)
      || item.timestamp_from < 0 || item.timestamp_to <= item.timestamp_from) {
      throw new Error(`${reciter} ${expectedKey}: invalid range`);
    }
    return [item.timestamp_from, item.timestamp_to];
  });
}

const byReciter = {};
for (const [reciter, apiId] of Object.entries(RECITERS)) {
  byReciter[reciter] = [null];
  for (let surah = 1; surah <= 114; surah++) {
    byReciter[reciter].push(await fetchRanges(apiId, reciter, surah));
    process.stdout.write(`\rContinuous ranges: ${reciter} ${surah}/114`);
  }
}
process.stdout.write('\n');

const lines = [
  '// Auto-generated by scripts/gen/fetch-qurancom-ayah-ranges.mjs.',
  '// Source: api.qurancdn.com audio_files verse_timings.',
  '// Index: [reciter][surah][ayah - 1] = [startMs, endMs].',
  '',
  "import type { ReciterId } from '../lib/reciters';",
  '',
  'type Range = readonly [startMs: number, endMs: number];',
  'type SurahRanges = readonly (readonly Range[])[];',
  '',
  'export const QURANCOM_AYAH_RANGES_MS: Partial<Record<ReciterId, SurahRanges>> = {',
];
for (const reciter of Object.keys(RECITERS)) {
  lines.push(`  ${reciter}: [`);
  lines.push('    [],');
  for (let surah = 1; surah <= 114; surah++) {
    const packed = byReciter[reciter][surah]
      .map(([start, end]) => `[${start},${end}]`)
      .join(',');
    lines.push(`    [${packed}], // ${surah}`);
  }
  lines.push('  ],');
}
lines.push('};', '');
writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT}`);
