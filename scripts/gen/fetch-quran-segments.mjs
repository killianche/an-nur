#!/usr/bin/env node
/**
 * fetch-quran-segments.mjs
 *
 * Pulls word-level segment timings from the public Qurancdn API for
 * EVERY reciter we ship in `web/src/lib/reciters.ts`, and writes them
 * to `web/src/content/quran-segments.ts` keyed by reciter id. The
 * client picks the right bucket at playback time so the karaoke
 * marker tracks the actual cadence of whoever is reciting.
 *
 *   GET https://api.qurancdn.com/api/qdc/audio/reciters/{recId}/audio_files
 *       ?chapter={N}&segments=true
 *
 * No OAuth — endpoint is public. Surah-relative timings are shifted to
 * verse-relative on the way out so consumers don't need to know.
 *
 * RECITER_MAP below pairs our reciter ids with quran.com recitation_ids.
 * Reciters not on quran.com (e.g. Maher Al-Muaiqly) are skipped — the
 * client gracefully degrades to "no word highlight" when audio plays for
 * a reciter without segment data.
 *
 * Run: node scripts/fetch-quran-segments.mjs   (Node 18+ for global fetch)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SURAHS_TS = resolve(ROOT, 'web/src/content/surahs.ts');
const OUT_PATH  = resolve(ROOT, 'web/src/content/quran-segments.ts');

const API = 'https://api.qurancdn.com/api/qdc/audio/reciters';

/**
 * Maps our internal ReciterId (web/src/lib/reciters.ts) to the
 * quran.com recitation_id served by the qurancdn API. Reciters not
 * present on quran.com are omitted — the client falls back to no
 * word-level highlight for them.
 */
const RECITER_MAP = {
  alafasy:    7,    // Mishari Rashid al-`Afasy (Murattal)
  shaatree:   4,    // Abu Bakr al-Shatri
  husary:     6,    // Mahmoud Khalil Al-Husary (Murattal)
  abdulbasit: 2,    // AbdulBaset AbdulSamad (Murattal)
  hanirifai:  5,    // Hani ar-Rifai
  shuraim:   10,    // Sa'ud ash-Shuraim
  yasser:    97,    // Yasser Ad-Dussary
  tunaiji:  161,    // Khalifah Al Tunaiji
  // Removed at user request (May 2026):
  //   sudais (id 3)        — taking off the picker
  //   mahermuaiqly         — was never on quran.com; no segments anyway
};

function extractSurahsWithContent() {
  const src = readFileSync(SURAHS_TS, 'utf-8');
  const m = src.match(/SURAHS_WITH_CONTENT\s*=\s*new Set\(\s*\[([^\]]+)\]\)/);
  if (!m) throw new Error('SURAHS_WITH_CONTENT not found in surahs.ts');
  return m[1]
    .split(',')
    .map(s => s.trim())
    .filter(Boolean)
    .map(Number)
    .filter(n => Number.isInteger(n) && n >= 1 && n <= 114);
}

async function fetchChapterTimings(reciterApiId, chapter) {
  const url = `${API}/${reciterApiId}/audio_files?chapter=${chapter}&segments=true`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for reciter ${reciterApiId} chapter ${chapter}`);
  const data = await res.json();
  const af = (data.audio_files ?? [])[0];
  if (!af) throw new Error(`no audio_files for reciter ${reciterApiId} chapter ${chapter}`);
  return af.verse_timings ?? [];
}

/** Convert surah-relative segments to verse-relative ms; drop pause segments. */
function normaliseVerse(verseTiming) {
  const start = verseTiming.timestamp_from;
  const segments = (verseTiming.segments ?? [])
    .filter(seg => seg[0] > 0)
    .map(([wordPos, sMs, eMs]) => [wordPos, sMs - start, eMs - start]);
  return { key: verseTiming.verse_key, segments };
}

function emitTs(byReciter) {
  const lines = [
    `// Auto-generated by scripts/fetch-quran-segments.mjs.`,
    `// Source: api.qurancdn.com /api/qdc/audio/reciters/{id}/audio_files.`,
    `// Each reciter bucket holds verse-relative [wordPos1based, startMs, endMs]`,
    `// segments aligned to that reciter's own cadence — picked by the playback`,
    `// hook so the karaoke marker tracks whoever is currently reciting.`,
    `// Re-run the script after adding a new surah to SURAHS_WITH_CONTENT or`,
    `// pairing a new reciter id with a quran.com recitation_id.`,
    ``,
    `import { type ReciterId } from '../lib/reciters';`,
    ``,
    `export type SegmentTuple = [wordPos: number, startMs: number, endMs: number];`,
    ``,
    `export type SegmentEntry = { segments: SegmentTuple[] };`,
    ``,
    `/** Reciters present on quran.com — others (e.g. Maher Al-Muaiqly) get`,
    ` *  no word-level highlight; the client falls back gracefully. */`,
    `export const QURAN_SEGMENTS: Partial<Record<ReciterId, Record<string, SegmentEntry>>> = {`,
  ];
  const reciterIds = Object.keys(byReciter).sort();
  for (const rec of reciterIds) {
    lines.push(`  ${rec}: {`);
    const verseKeys = Object.keys(byReciter[rec]).sort(sortVerseKeys);
    for (const key of verseKeys) {
      const segs = byReciter[rec][key];
      const inner = segs.map(([w, a, b]) => `[${w},${a},${b}]`).join(', ');
      lines.push(`    '${key}': { segments: [${inner}] },`);
    }
    lines.push(`  },`);
  }
  lines.push(`};`);
  lines.push(``);
  lines.push(`/** Look up the segments for a (reciter, verse) pair. Returns null when`);
  lines.push(` *  the reciter has no segment bucket (e.g. Maher Al-Muaiqly) or the`);
  lines.push(` *  verse hasn't been fetched yet — caller should disable the marker. */`);
  lines.push(`export function getQuranSegments(reciter: ReciterId, verseKey: string): SegmentEntry | null {`);
  lines.push(`  return QURAN_SEGMENTS[reciter]?.[verseKey] ?? null;`);
  lines.push(`}`);
  lines.push(``);
  return lines.join('\n');
}

function sortVerseKeys(a, b) {
  const [s1, a1] = a.split(':').map(Number);
  const [s2, a2] = b.split(':').map(Number);
  return s1 !== s2 ? s1 - s2 : a1 - a2;
}

async function main() {
  const chapters = extractSurahsWithContent();
  const reciterIds = Object.keys(RECITER_MAP);
  console.log(`fetching segments for chapters: ${chapters.join(', ')}`);
  console.log(`reciters: ${reciterIds.join(', ')}`);

  const byReciter = {};
  for (const rec of reciterIds) {
    const apiId = RECITER_MAP[rec];
    byReciter[rec] = {};
    let total = 0;
    for (const ch of chapters) {
      try {
        const verseTimings = await fetchChapterTimings(apiId, ch);
        let count = 0;
        for (const vt of verseTimings) {
          const { key, segments } = normaliseVerse(vt);
          byReciter[rec][key] = segments;
          count++;
        }
        console.log(`  ${rec.padEnd(12)} ch ${ch}: ${count} ayahs`);
        total += count;
      } catch (err) {
        console.warn(`  ${rec.padEnd(12)} ch ${ch}: FAILED — ${err.message}`);
      }
    }
    console.log(`  ${rec.padEnd(12)} TOTAL: ${total} ayah(s)`);
  }

  writeFileSync(OUT_PATH, emitTs(byReciter), 'utf-8');
  const sizes = reciterIds.map(r => `${r}=${Object.keys(byReciter[r]).length}`).join(', ');
  console.log(`wrote ${OUT_PATH}`);
  console.log(`buckets: ${sizes}`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
