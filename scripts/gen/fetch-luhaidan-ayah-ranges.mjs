#!/usr/bin/env node
/**
 * Fetch compact ayah boundaries for Muhammad Al-Luhaidan's full-surah audio.
 *
 * Source JSON: m7mdiyat-tafsir-data/timings/luhaidan/{surah}.json
 * Audio:       server8.mp3quran.net/lhdan/{SSS}.mp3
 *
 * The source's detailed alignment files name the same MP3Quran recordings and
 * report durations matching them. We store only [startMs,endMs] pairs; runtime
 * playback therefore needs no timing network request before audio.play().
 *
 * Run: node scripts/gen/fetch-luhaidan-ayah-ranges.mjs
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '../..');
const OUT = resolve(ROOT, 'src/content/luhaidan-ayah-ranges.ts');
const BASE = 'https://storage.googleapis.com/m7mdiyat-tafsir-data/timings/luhaidan';
const COUNTS = [
  7,286,200,176,120,165,206,75,129,109,123,111,43,52,99,128,111,110,98,135,
  112,78,118,64,77,227,93,88,69,60,34,30,73,54,45,83,182,88,75,85,54,53,89,
  59,37,35,38,29,18,45,60,49,62,55,78,96,29,22,24,13,14,11,11,18,12,12,30,
  52,52,44,28,28,20,56,40,31,50,40,46,42,29,19,36,25,22,17,19,26,30,20,15,
  21,11,8,8,19,5,8,8,11,11,8,3,9,5,4,7,3,6,3,5,4,5,6,
];

async function fetchSurah(surah) {
  const response = await fetch(`${BASE}/${surah}.json`);
  if (!response.ok) throw new Error(`HTTP ${response.status} for surah ${surah}`);
  const data = await response.json();
  if (data.surah !== surah || !Array.isArray(data.ayahs)) {
    throw new Error(`invalid schema for surah ${surah}`);
  }
  if (data.ayahs.length !== COUNTS[surah - 1]) {
    throw new Error(`surah ${surah}: ${data.ayahs.length} ranges, expected ${COUNTS[surah - 1]}`);
  }
  return data.ayahs.map((item, index) => {
    if (item.ayah !== index + 1 || !Number.isInteger(item.start)
      || !Number.isInteger(item.end) || item.start < 0 || item.end <= item.start) {
      throw new Error(`invalid range at ${surah}:${index + 1}`);
    }
    return [item.start, item.end];
  });
}

const ranges = [null];
for (let surah = 1; surah <= 114; surah++) {
  ranges.push(await fetchSurah(surah));
  process.stdout.write(`\rLuhaidan timings: ${surah}/114`);
}
process.stdout.write('\n');

const lines = [
  '// Auto-generated by scripts/gen/fetch-luhaidan-ayah-ranges.mjs.',
  '// Source: storage.googleapis.com/m7mdiyat-tafsir-data/timings/luhaidan/{surah}.json',
  '// Audio: server8.mp3quran.net/lhdan/{SSS}.mp3',
  '// Index: [surah][ayah - 1] = [startMs, endMs]. Index 0 is unused.',
  '',
  'export const LUHAIDAN_AYAH_RANGES_MS: readonly (readonly (readonly [number, number])[])[] = [',
  '  [],',
];
for (let surah = 1; surah <= 114; surah++) {
  lines.push(`  [${ranges[surah].map(([start, end]) => `[${start},${end}]`).join(',')}], // ${surah}`);
}
lines.push('];', '');
writeFileSync(OUT, lines.join('\n'), 'utf8');
console.log(`Wrote ${OUT}`);
