/**
 * Доводка листа после отпускания пальца.
 *
 * 🔴 Длительность НЕ фиксированная, и это главное здесь.
 *
 * Раньше стояло 220 мс на любой случай, и лист от этого дёргался в обе
 * стороны. Отпустишь у самого края, когда пройти осталось десяток
 * пикселей, — он всё равно полз положенные 220 мс. Бросишь быстрым
 * движением с середины — пролетал почти всю ширину за то же время, и это
 * читалось как рывок, а не как продолжение жеста.
 *
 * Правильно — считать время от того, сколько ОСТАЛОСЬ пройти, и учитывать
 * скорость пальца. Но деление «базового времени» на скорость укорачивало
 * доводку до минимума 130 мс при быстром флике — лист телепортировал
 * почти весь экран. Скорость пальца оправдывает продолжение движения, а
 * не телепортацию: ниже — потолок скорости листа (px/мс), он задаёт
 * нижнюю границу длительности.
 *
 * 🔴 Следствие потолка, которое нужно знать заранее, иначе оно выглядит
 * как поломка. Когда идти осталось много, потолок оказывается сильнее
 * скорости пальца, и быстрый бросок перестаёт отличаться от спокойного
 * отпускания: на ширине 390 полная ширина даёт 340 и 325 мс, а на 430–440
 * (Plus и Pro Max) — одинаковые 358 и 367 мс. Это не потеря скорости, а её
 * ограничение: лист идёт ровно 1.2 px/мс вместо прежних 3.3 px/мс. По той
 * же причине обещанные «340 мс на полную ширину» точны только там, где
 * ширина не больше 408 px; дальше время растёт вместе с путём, и так и
 * должно быть — экран шире, дорога длиннее.
 */
/*
 * 🔴 Числа подняты 05.09.2026 по просьбе владельца: «важно, чтобы доводка была
 * суперплавной, не быстрой, даже достаточно медленной». Было 340/130/420 при
 * потолке 1.2 px/мс — лист доезжал бодро. Стало 520/200/760 при потолке
 * 0.75 px/мс: полная ширина занимает больше полусекунды, и никакой бросок
 * этого не ускорит.
 *
 * 06.09.2026 замедлено ещё раз, снова по просьбе владельца: было 520/200/760
 * при потолке 1.0, стало 780/300/1200 при потолке 0.65. Полная ширина теперь
 * 780 мс при спокойном отпускании и 600 мс при броске — лист именно доплывает.
 *
 * Потолок именно 1.0, а не меньше: при 0.75 он в точности совпал с базовой
 * скоростью (520 мс на 390 px — те же 0.75 px/мс), и скорость пальца
 * переставала влиять вовсе — расчёт становился мёртвым кодом. Тесты это и
 * поймали. При 1.0 спокойное отпускание на полной ширине даёт 520 мс, бросок
 * — 390 мс: разница есть, но медленно в обоих случаях.
 */
/** Время на полную ширину экрана при отпускании без скорости. */
const PAGE_TURN_FULL_MS = 780;
/** Границы: ниже первой доводка незаметна, выше второй — вязнет. */
const PAGE_TURN_MIN_MS = 300;
const PAGE_TURN_MAX_MS = 1200;
/** Быстрее этого лист не едет. Пикселей в миллисекунду. */
const PAGE_TURN_SPEED_CAP = 0.65;

/**
 * Сколько миллисекунд дать доводке.
 *
 * `velocity` — в пикселях за миллисекунду, как её считает `onTouchEnd`.
 * Экспортируется для тестов: правило легко сломать незаметно, потому что
 * ошибка выглядит не как поломка, а как «что-то не так с анимацией».
 */
export function pageTurnDuration(
  remainingPx: number,
  widthPx: number,
  velocity: number,
): number {
  const width = Math.max(1, widthPx);
  const remaining = Math.abs(remainingPx);
  const share = Math.min(1, remaining / width);
  // Скорость выше 3 px/мс уже не ускоряет дальше по «дослушиванию».
  const speedUp = 1 + Math.min(Math.abs(velocity), 3) * 0.9;
  let raw = (PAGE_TURN_FULL_MS * share) / speedUp;
  // Потолок скорости листа: не финишировать раньше, чем remaining / CAP.
  raw = Math.max(raw, remaining / PAGE_TURN_SPEED_CAP);
  return Math.round(Math.min(PAGE_TURN_MAX_MS, Math.max(PAGE_TURN_MIN_MS, raw)));
}
