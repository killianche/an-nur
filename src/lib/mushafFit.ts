/**
 * mushafFit — правила подгонки страницы мусхафа под экран.
 *
 * Здесь только арифметика: замер живёт в `components/QcfMushafPage.tsx`,
 * потому что читать вёрстку можно лишь из DOM. Вынесено ради проверяемости —
 * обе ошибки, найденные 09.09.2026, были именно в правилах, а не в чтении.
 */

/**
 * С какой заполненности строка считается набранной и тянется по ширине.
 *
 * Замер идёт по естественной ширине слов: у глифов QCF боковые отступы уже
 * внутри, поэтому своего зазора вёрстка не добавляет — добавленный заставлял
 * строки переполняться и сбивал подбор кегля.
 *
 * 0.9 отделяет набранную строку от короткой: последняя строка суры и строки
 * Аль-Фатихи заполняют меньше, обычная строка мусхафа — больше.
 */
export const JUSTIFY_FILL = 0.9;

/** Ниже этого превышения поправка не стоит лишней перерисовки. */
export const FIT_TOLERANCE = 1.002;

/**
 * Сколько поправок кегля разрешено сделать.
 *
 * Ширина глифа зависит от кегля почти линейно, но не совсем: продвижения
 * округляются под пиксельную сетку, и после первой поправки остаётся невязка
 * в доли процента. Прежних двух проходов на неё не хватало, и строки
 * Аль-Фатихи вставали на 1–3px за полосу набора при поле в 4px.
 */
export const MAX_FIT_PASSES = 3;

/**
 * Во сколько раз ужать кегль, чтобы страница влезла. 1 — уже влезла.
 *
 * `fills` — заполнение каждой строки: ширина набора, делённая на ширину
 * полосы. Больше единицы значит, что строка вылезла за полосу.
 */
export function fitScale(fills: number[], heightRatio = 1): number {
  const ratio = Math.max(1, heightRatio, ...fills);
  return ratio > FIT_TOLERANCE ? ratio : 1;
}

/**
 * Тянуть ли строку по ширине.
 *
 * Строка из одного слова — никогда: это заголовок суры или басмала, они
 * стоят по центру.
 */
export function lineJustified(fill: number, wordCount: number): boolean {
  return wordCount >= 2 && fill >= JUSTIFY_FILL;
}
