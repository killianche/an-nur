/**
 * Возврат из аварийного поаятного режима на сплошную запись суры.
 *
 * ── Задача ────────────────────────────────────────────────────────────
 *
 * Если сплошная запись не открылась (обрыв потока, мёртвая сеть), плеер
 * доигрывает суру поаятными файлами с диска — иначе чтение бы встало. Но
 * поаятный режим звучит со швом на каждом аяте: каждый аят — отдельный файл
 * со своей тишиной по краям и отдельным запуском элемента.
 *
 * Прежде этот режим был липким до конца суры. Одной осечки сети хватало,
 * чтобы вся оставшаяся сура — у Аль-Бакары это часы — шла со швами. Замер в
 * симуляторе iOS 13.09.2026: сплошная запись недоступна, на диске старые
 * поаятные файлы суры 83 — все 30 следующих аятов сыграли отдельными
 * файлами. Владелец слышал это как «прерывание между аятами».
 *
 * Теперь плеер в фоне проверяет, открывается ли сплошная запись снова, и на
 * ближайшей границе аята возвращается на неё.
 *
 * ── Почему пауза растёт ───────────────────────────────────────────────
 *
 * Возврат, который тут же срывается, стоит дорого: сторож ждёт звука, потом
 * повтор, потом снова поаятный режим — секунды тишины посреди чтения. На
 * мигающей сети это повторялось бы каждые несколько секунд. Поэтому каждая
 * неудача в той же суре удваивает паузу перед следующей проверкой, до
 * предела в две минуты.
 */

/** Первая пауза перед проверкой сплошной записи после отказа. */
export const RECOVERY_FIRST_DELAY_MS = 10_000;

/** Больше этого ждать не нужно: две минуты шва — уже заметная цена. */
export const RECOVERY_MAX_DELAY_MS = 120_000;

/** Сколько ждать заголовка файла, прежде чем признать проверку неудачной. */
export const RECOVERY_PROBE_TIMEOUT_MS = 10_000;

/**
 * Пауза перед проверкой номер `attempt` (с единицы) в одной и той же суре.
 *
 * `attempt` считает все неудачи этой суры — и отказ самой записи, и
 * несостоявшиеся проверки. 10 с, 20 с, 40 с, 80 с, дальше 120 с.
 */
export function recoveryDelayMs(attempt: number): number {
  const n = Number.isFinite(attempt) ? Math.max(1, Math.floor(attempt)) : 1;
  // Степень ограничена заранее: 2 ** 1000 — это Infinity, и Math.min спас бы
  // результат, но считать такое незачем.
  const степень = Math.min(n - 1, 16);
  return Math.min(RECOVERY_FIRST_DELAY_MS * 2 ** степень, RECOVERY_MAX_DELAY_MS);
}
