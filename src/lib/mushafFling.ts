/**
 * mushafFling — движение листа мусхафа как физика, а не как переход CSS.
 *
 * ── Почему переписано ─────────────────────────────────────────────────
 *
 * Было: доводка — CSS-переход фиксированной длительности. Новое касание
 * обрывало его вызовом `finish()`, который мгновенно ставил смещение в ноль
 * и фиксировал страницу. Но лист в этот момент стоял на полпути, и он
 * ПРЫГАЛ на оставшееся расстояние. Владелец 10.09.2026 описал это точно:
 * «пока одна не закончилась перелистываться, когда мы ещё листаем, в этот
 * момент происходит дёргания… анимация конфликтует».
 *
 * Скорость пальца при этом на движение не влияла вовсе — только на
 * длительность перехода, да и ту ограничивал потолок. Быстрый бросок и
 * спокойное отпускание выглядели одинаково.
 *
 * Стало: положение листа считается каждый кадр. Отпущенный лист летит с той
 * скоростью, с какой его вели, и притягивается к ближайшей границе страницы.
 * Новое касание ничего не обрывает — оно ПЕРЕХВАТЫВАЕТ движение вместе с
 * текущей скоростью, как системная прокрутка iOS и как листалки читалок.
 *
 * ── Почему пружина, а не трение ───────────────────────────────────────
 *
 * Листу нужно прийти ровно на границу страницы, а не «куда вынесет». Это
 * задача не свободного скольжения, а притяжения к цели. Пружина в
 * критическом затухании приходит к цели за кратчайшее время БЕЗ перелёта:
 * страница не отскакивает назад — бумага так себя не ведёт.
 *
 * Шаг считается точной формулой, а не численным интегрированием: при
 * пропущенном кадре (а они случаются) Эйлер накапливает ошибку и может
 * разогнать пружину, а закрытая форма верна при любом dt.
 */

/** Состояние листа: смещение в px и скорость в px/мс. */
export type FlingState = { x: number; v: number };

/**
 * Самое медленное возвращение, мс. Постоянная времени, а не длительность:
 * лист проходит за неё примерно две трети пути, а весь путь — за ~6.4 τ.
 *
 * 125 мс дают спокойные ~800 мс на три четверти экрана.
 *
 * 🔴 Прежние 1560 мс сюда НЕ переносятся, и это не потеря настройки
 * владельца. Та медленность была лекарством от несуществующей теперь
 * болезни: доводку нельзя было продолжить, её можно было только оборвать,
 * и чем она дольше, тем мягче выглядела. Движение, которое можно
 * перехватить в любой момент, при такой длительности читается уже не как
 * плавность, а как вязкость.
 */
export const TAU_MAX = 125;

/** Самое быстрое: сильный бросок проходит три четверти экрана за ~290 мс. */
export const TAU_MIN = 45;

/**
 * Сколько миллисекунд движения «в кредит» даёт скорость пальца при выборе
 * страницы.
 *
 * Это перенос прежних двух правил в одно. Раньше страница переворачивалась
 * при пути ≥ порога ИЛИ при коротком быстром движении (≥20 px и ≥0.48 px/мс).
 * Теперь решает предсказанная точка остановки: щелчок на 40 px со скоростью
 * 1 px/мс добавляет к пути 80 и порог берёт, а протяжка на 150 px берёт его
 * и без всякой скорости.
 *
 * 🔴 80, а не 260. При 260 кредит перевешивал сам путь: вялая протяжка на
 * 50 px со скоростью 0.21 px/мс получала +55 и переворачивала страницу,
 * хотя прежний код на такой жест не реагировал — а это половина порога и
 * восьмая часть экрана. Листать от неосторожного движения в мусхафе плохо:
 * место в чтении теряется. Проверено вживую, тесты этого не поймали — там
 * такого жеста не было, теперь есть.
 */
export const PROJECT_MS = 80;

/** Быстрее этого лист не летит: бросок продолжает жест, а не телепортирует. */
export const MAX_SPEED = 4.5;

/**
 * Ниже этого смещения направление жеста решает скорость, а не путь.
 *
 * Нужно для щелчка почти без движения: пальцем сдвинули на пару пикселей
 * влево, а бросили вправо — направление задаёт бросок.
 */
const DEAD_ZONE = 12;

/**
 * Куда лист поедет после отпускания: 0 — назад на место, ±step — на
 * соседнюю страницу.
 *
 * За один жест ровно одна страница. Инерция на несколько страниц вперёд для
 * мусхафа вредна: место в чтении теряется, а вернуться к нему тяжело.
 * Скорость влияет на то, КАК БЫСТРО лист придёт, а не сколько страниц
 * пролистнётся.
 *
 * 🔴 Переворот разрешён только в сторону самого жеста. Без этого правила
 * протяжка вперёд на 90 px, законченная резким броском назад, уводила на
 * ПРЕДЫДУЩУЮ страницу: предсказание улетало за порог в другую сторону.
 * Формально это «инерция», на деле — жест, начатый как «вперёд», отдавал
 * страницу назад. В мусхафе такой сюрприз стоит потерянного места.
 */
export function projectTarget(
  x: number,
  v: number,
  step: number,
  threshold: number,
  { canForward = true, canBack = true }: { canForward?: boolean; canBack?: boolean } = {},
): number {
  const направление = Math.abs(x) >= DEAD_ZONE ? Math.sign(x) : Math.sign(v);
  if (направление === 0) return 0;
  const projected = x + clampSpeed(v) * PROJECT_MS;
  if (Math.sign(projected) !== направление) return 0;
  if (Math.abs(projected) < threshold) return 0;
  if (направление > 0) return canForward ? step : 0;
  return canBack ? -step : 0;
}

/**
 * Постоянная времени для полёта: чем быстрее отпустили, тем короче.
 *
 * 🔴 Приближение экспоненциальное, а не пружинное, и это принципиально.
 * Пружина в критическом затухании при сильном броске ПЕРЕЛЕТАЕТ цель и
 * возвращается — на экране это резинка, а бумага так себя не ведёт: лист
 * доходит до места и остаётся там. Экспонента монотонна по построению,
 * перелёт в ней невозможен вообще, а скорость пальца входит в неё
 * естественно — через время, за которое лист пройдёт остаток.
 */
export function approachTau(distance: number, speed: number): number {
  const путь = Math.abs(distance);
  const скорость = Math.abs(clampSpeed(speed));
  if (путь < 0.5) return TAU_MIN;
  if (скорость < 0.01) return TAU_MAX;
  // Начальная скорость экспоненты равна путь/τ — отсюда и берём τ.
  return Math.max(TAU_MIN, Math.min(TAU_MAX, путь / скорость));
}

/**
 * Состояние через `dt` мс: x(t) = target + (x₀ − target)·e^(−t/τ).
 *
 * Закрытая форма, а не численное интегрирование: пропущенный кадр не
 * накапливает ошибку и не разгоняет движение, а они случаются.
 */
export function stepFling(
  state: FlingState,
  target: number,
  dt: number,
  tau = TAU_MAX,
): FlingState {
  const t = Math.max(0, Math.min(dt, 64));   // пропущенные кадры не разгоняют
  const τ = Math.max(1, tau);
  const остаток = (state.x - target) * Math.exp(-t / τ);
  return { x: target + остаток, v: -остаток / τ };
}

/** Лист пришёл: и стоять осталось меньше полпикселя, и скорость погасла. */
export function isSettled(state: FlingState, target: number): boolean {
  return Math.abs(state.x - target) < 0.5;
}

/** Скорость пальца, ограниченная потолком и очищенная от мусора. */
export function clampSpeed(v: number): number {
  if (!Number.isFinite(v)) return 0;
  return Math.max(-MAX_SPEED, Math.min(MAX_SPEED, v));
}
