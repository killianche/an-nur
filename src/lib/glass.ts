/**
 * glass — размытие фона для плавающих панелей.
 *
 * ── 🔴 Почему это здесь, а не в CSS-классе ────────────────────────────
 *
 * Потому что из CSS оно не доезжает. Стили проекта проходят через
 * Lightning CSS (его подключает плагин Tailwind), и он переписывает
 * `backdrop-filter` по своим представлениям о целевых браузерах: в сборке
 * остаётся только `-webkit-backdrop-filter`, а свойство без префикса
 * пропадает. Chrome и Android WebView в свежих версиях префиксную форму в
 * CSSOM уже не поднимают, и `getComputedStyle(...).backdropFilter` честно
 * отвечает `none` — то есть размытия нет вовсе.
 *
 * Проверено на собранном `dist`: правило класса приезжало без свойства без
 * префикса, панель оставалась просто полупрозрачной, и содержимое под ней
 * читалось насквозь.
 *
 * Инлайновый стиль минификатор не трогает — React ставит оба свойства как
 * есть. Отсюда и общий объект: иначе рецепт стекла разъедется между
 * панелями, а разницу видно, когда они на экране вместе.
 *
 * Остальное оформление стекла (материал, грань, блик, тени) живёт в классе
 * `.liquid-glass` в `index.css` — там минификатор ничего не ломает.
 */

/** Размытие и насыщение фона под стеклом. Ставится инлайном. */
export const GLASS_BLUR = {
  backdropFilter: 'saturate(var(--saturate-chrome)) blur(var(--blur-chrome))',
  WebkitBackdropFilter: 'saturate(var(--saturate-chrome)) blur(var(--blur-chrome))',
} as const;
