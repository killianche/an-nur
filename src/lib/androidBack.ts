/**
 * Аппаратная кнопка «назад» на Android.
 *
 * ── Что было сломано ──────────────────────────────────────────────────
 *
 * Ничего не связывало системную кнопку с историей приложения, и первое
 * же нажатие «назад» — с экрана суры, закладок, откуда угодно —
 * выбрасывало на рабочий стол.  Поймано живым прогоном на эмуляторе:
 * навигация внутри приложения идёт через History API, но по умолчанию
 * Capacitor просто закрывает активити, до JS событие не доходит.
 *
 * На Android это грубая ошибка: «назад» — основной способ навигации,
 * и приложение, которое от неё закрывается, ощущается сломанным.
 *
 * ── Как решено ────────────────────────────────────────────────────────
 *
 * Подписываемся на `backButton` у @capacitor/app и решаем сами, а не
 * доверяем `canGoBack` из плагина: тот отражает состояние истории
 * WebView, а нам нужно наше собственное понятие «корня».
 *
 * Признак корня — поле `root` в `history.state`, которое App.tsx
 * ставит на самую первую запись.  Любая запись глубже (переход на
 * экран, открытый попап настроек) корнем не помечена, значит есть
 * куда возвращаться.
 *
 * В корне сворачиваем приложение, а не закрываем: это читалка с
 * аудио, и «назад» на первом экране во время чтения суры не должно
 * обрывать воспроизведение.  Сворачивание оставляет процесс живым —
 * звук продолжается, возврат мгновенный.
 *
 * На iOS слушатель не навредит — там аппаратной кнопки просто нет и
 * событие не приходит.
 */

import { App as CapApp } from '@capacitor/app';

/** Ставит обработчик.  Возвращает функцию снятия. */
export function wireAndroidBackButton(): () => void {
  let removed = false;
  // addListener асинхронный: держим промис, чтобы корректно снять
  // подписку, даже если размонтирование случилось раньше её создания.
  const handle = CapApp.addListener('backButton', () => {
    if (history.state?.root) {
      // Корень — уходим на рабочий стол, но остаёмся в памяти.
      void CapApp.minimizeApp();
      return;
    }
    history.back();
  });

  return () => {
    if (removed) return;
    removed = true;
    void handle.then(h => h.remove());
  };
}
