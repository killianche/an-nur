/**
 * Сквозная нумерация аятов 1..6236.
 *
 * Вынесено в отдельный листовой модуль, чтобы разорвать цикл
 * `quranUtils → audioStore → quranUtils`: разрешение URL аята должно
 * спросить реестр скачанного, а реестру нужен сквозной номер.  ESM
 * такой цикл обычно переживает (обращения происходят во время вызова,
 * а не инициализации), но это ровно тот класс зависимостей, который
 * ломается молча и в проде — при перестановке импортов или смене
 * порядка чанков в бандле.  Модуль без единого импорта не может
 * оказаться в цикле по определению.
 */

/** Количество аятов в каждой суре, 1..114. */
const AYAHS_PER_SURAH = [
  7,286,200,176,120,165,206,75,129,109,123,111,43,52,99,128,111,110,98,135,
  112,78,118,64,77,227,93,88,69,60,34,30,73,54,45,83,182,88,75,85,54,53,89,
  59,37,35,38,29,18,45,60,49,62,55,78,96,29,22,24,13,14,11,11,18,12,12,30,
  52,52,44,28,28,20,56,40,31,50,40,46,42,29,19,36,25,22,17,19,26,30,20,15,
  21,11,8,8,19,5,8,8,11,11,8,3,9,5,4,7,3,6,3,5,4,5,6,
];

/** Всего аятов в Коране. */
export const TOTAL_AYAHS = 6236;

/**
 * Префиксные суммы: FIRST_GLOBAL[s] — сквозной номер первого аята
 * суры s (1-based, индекс 0 не используется).
 *
 * Раньше globalAyahNumber складывал длины сур циклом — до 113
 * итераций на вызов.  Само по себе дёшево, но функция оказалась в
 * горячем пути: сортировка списка загрузки звала её десятки тысяч раз
 * за один рендер, и это выливалось в 50-200 мс фриза на телефоне.
 * Таблица считается один раз при загрузке модуля.
 */
const FIRST_GLOBAL: number[] = (() => {
  const out = new Array<number>(AYAHS_PER_SURAH.length + 2);
  let acc = 1;
  for (let s = 1; s <= AYAHS_PER_SURAH.length; s++) {
    out[s] = acc;
    acc += AYAHS_PER_SURAH[s - 1];
  }
  out[AYAHS_PER_SURAH.length + 1] = acc;   // страж = TOTAL_AYAHS + 1
  return out;
})();

/** «сура:аят» → сквозной номер 1..6236.  O(1). */
export function globalAyahNumber(surah: number, ayah: number): number {
  return (FIRST_GLOBAL[surah] ?? 1) + ayah - 1;
}

/** Сколько аятов в суре (0 для номера вне 1..114). */
export function ayahsInSurah(surah: number): number {
  return AYAHS_PER_SURAH[surah - 1] ?? 0;
}

/** Сквозной номер первого аята суры.  O(1). */
export function firstGlobalOfSurah(surah: number): number {
  return FIRST_GLOBAL[surah] ?? 1;
}

/** Всего сур. */
export const TOTAL_SURAHS = 114;

/**
 * Границы джузов по началу: [сура, аят] начала каждого из 30 джузов.
 * Нужны, чтобы предлагать скачивание джузом — привычная для читателя
 * единица, промежуточная между сурой и всем Кораном.
 *
 * Источник: стандартное деление мусхафа (King Fahd Complex), сверено
 * с таблицей джузов на quran.com.
 */
const JUZ_STARTS: readonly (readonly [number, number])[] = [
  [1, 1],    [2, 142],  [2, 253],  [3, 93],   [4, 24],
  [4, 148],  [5, 82],   [6, 111],  [7, 88],   [8, 41],
  [9, 93],   [11, 6],   [12, 53],  [15, 1],   [17, 1],
  [18, 75],  [21, 1],   [23, 1],   [25, 21],  [27, 56],
  [29, 46],  [33, 31],  [36, 28],  [39, 32],  [41, 47],
  [46, 1],   [51, 31],  [58, 1],   [67, 1],   [78, 1],
];

/** Сквозной диапазон джуза 1..30 — [первый, последний] включительно. */
export function juzRange(juz: number): [number, number] {
  const i = Math.min(30, Math.max(1, Math.floor(juz))) - 1;
  const from = globalAyahNumber(JUZ_STARTS[i][0], JUZ_STARTS[i][1]);
  const to = i === 29
    ? TOTAL_AYAHS
    : globalAyahNumber(JUZ_STARTS[i + 1][0], JUZ_STARTS[i + 1][1]) - 1;
  return [from, to];
}
