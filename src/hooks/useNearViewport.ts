/**
 * useNearViewport — близко ли элемент к экрану.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────
 *
 * Сура монтируется целиком: useChunkedRender добавляет аяты батчами,
 * пока в DOM не окажутся все — этого требуют восстановление прокрутки,
 * синхронизация с аудио и переход по якорю.  Для разметки это правильно,
 * но для шрифтов губительно: `@font-face` плюс текст в DOM означает
 * немедленную загрузку, и Ан-Ниса разом просила 32 подмножества.
 *
 * Браузер честно делил канал между всеми, и файл, нужный ПЕРВОМУ экрану,
 * приходил вместе с последними — человек смотрел на скелет секунд
 * двадцать, хотя нужных ему байт было 84 КБ.
 *
 * Отсюда правило: подмножество просим только когда аят подошёл к экрану.
 * Первый экран получает свои два файла без соседей по очереди, остальное
 * подтягивается по мере чтения.
 *
 * ── Почему запас в полтора экрана ─────────────────────────────────────
 *
 * Шрифт страницы — около 70 КБ, то есть доли секунды.  Полтора экрана
 * запаса означают, что к моменту, когда аят доедет до глаз, текст уже
 * готов, и скелет человек видит только на первом экране при первом
 * открытии.  Больший запас вернул бы очередь из десятков файлов, меньший
 * — скелет во время прокрутки.
 *
 * ── Почему обратно не выключается ─────────────────────────────────────
 *
 * Единожды подошедший аят остаётся «близким» навсегда.  Шрифт уже
 * загружен и лежит в кэше; сняв признак, мы бы вернули на прокрученный
 * текст скелет и заставили страницу дёргаться при движении вверх-вниз.
 */

import { useEffect, useState, type RefObject } from 'react';

/** Запас вокруг экрана, в долях его высоты. */
const MARGIN_SCREENS = 1.5;

export function useNearViewport(
  ref: RefObject<Element | null>,
  enabled = true,
): boolean {
  const [near, setNear] = useState(false);

  useEffect(() => {
    if (!enabled || near) return;
    const el = ref.current;
    if (!el) return;

    // Без IntersectionObserver считаем близким всё: лучше показать текст
    // сразу, чем не показать никогда.
    if (typeof IntersectionObserver === 'undefined') {
      setNear(true);
      return;
    }

    const margin = Math.round(
      (typeof window !== 'undefined' ? window.innerHeight : 800) * MARGIN_SCREENS,
    );
    const io = new IntersectionObserver(
      entries => {
        if (entries.some(e => e.isIntersecting)) {
          setNear(true);
          io.disconnect();
        }
      },
      { rootMargin: `${margin}px 0px ${margin}px 0px` },
    );
    io.observe(el);
    return () => io.disconnect();
  }, [ref, enabled, near]);

  return near;
}
