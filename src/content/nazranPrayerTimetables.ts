const KEYS: readonly PrayerKey[] = [
  'fajr', 'sunrise', 'dhuhr', 'asr', 'maghrib', 'isha',
];

export function timetableRow(
  id: PrayerTimetableId,
  month: number,
  day: number,
): TimetableRow | null {
  const packed = RAW[id]?.[month]?.[day - 1];
  if (!packed) return null;
  const values = packed.split(' ');
  if (values.length !== KEYS.length) return null;
  return Object.fromEntries(KEYS.map((key, i) => [key, values[i]])) as TimetableRow;
}

export function timetableDays(id: PrayerTimetableId, month: number): number {
  return RAW[id]?.[month]?.length ?? 0;
}
