/**
 * SurahPlate — рамка вокруг названия суры на странице мусхафа.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────
 *
 * В печатном мусхафе начало суры не просто набрано крупнее — её название
 * стоит в золочёной рамке с орнаментом. Это не украшение ради украшения:
 * рамка отмечает границу, где кончилась одна сура и началась другая, и
 * взгляд находит её на развороте мгновенно, не читая текст. Владелец
 * прислал примеры арабских изданий именно с такой плашкой.
 *
 * ── Почему рисуем, а не берём картинку ────────────────────────────────
 *
 * Картинка была бы проще, но плашка обязана тянуться под ширину страницы,
 * а страница подстраивается под экран — от узкого телефона до планшета.
 * Растянутый растр даёт мыло на скруглениях и рвань на тонких линиях
 * орнамента. Вектор тянется без потерь и красится темой.
 *
 * ── Как устроено ──────────────────────────────────────────────────────
 *
 * Двойная рамка на всю ширину: линии рисуются рамкой и внутренней тенью,
 * поэтому всегда ровно в один пиксель, как бы ни растянулась плашка.
 *
 * Орнаментальные медальоны по краям были и сняты по решению владельца: в
 * маленьком кегле на телефоне узор читался не как печатное украшение, а
 * как посторонние значки у названия суры. Рамки достаточно, чтобы граница
 * суры находилась взглядом сразу.
 */

/**
 * Плашка целиком.
 *
 * `height` задаётся вызывающим от кегля страницы: рамка должна расти
 * вместе с текстом, иначе на планшете она окажется марочкой под крупным
 * названием.
 */
export function SurahPlate({
  height,
  children,
}: {
  height: number;
  children: React.ReactNode;
}) {
  return (
    <div
      style={{
        display: 'flex',
        alignItems: 'stretch',
        justifyContent: 'center',
        width: '100%',
        height: `${height}px`,
        // Плашка на странице стоит чуть свободнее строк — в печати вокруг
        // неё тоже оставляют воздух.
        margin: `${Math.round(height * 0.12)}px 0`,
      }}
    >
      {/* Середина: двойная рамка сверху и снизу плюс название по центру.
          Линии — border, а не SVG: так они всегда ровно в один пиксель,
          независимо от того, как растянулась середина. */}
      <div
        style={{
          flex: 1,
          minWidth: 0,
          position: 'relative',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          borderTop: '1.1px solid var(--gold)',
          borderBottom: '1.1px solid var(--gold)',
          // Вторая, внутренняя линия — тем же приёмом, тенью внутрь.
          boxShadow:
            'inset 0 3px 0 -2px var(--gold-soft), inset 0 -3px 0 -2px var(--gold-soft)',
          // Подложка теплее страницы: в печати внутри рамки бумага чуть
          // темнее от золотой краски по контуру.
          background: 'color-mix(in srgb, var(--gold) 7%, transparent)',
          overflow: 'hidden',
        }}
      >
        {children}
      </div>
    </div>
  );
}
