/**
 * SurahPlate — рамка вокруг названия суры на странице мусхафа.
 *
 * ── Зачем ─────────────────────────────────────────────────────────────
 *
 * В печатном мусхафе начало суры не просто набрано крупнее — её название
 * стоит в золочёной рамке с орнаментом. Это не украшение ради украшения:
 * рамка отмечает границу, где кончилась одна сура и началась другая, и
 * взгляд находит её на развороте мгновенно, не читая текст. Владелец
 * прислал примеры арабских изданий именно с такой плашкой.
 *
 * ── Почему рисуем, а не берём картинку ────────────────────────────────
 *
 * Картинка была бы проще, но плашка обязана тянуться под ширину страницы,
 * а страница подстраивается под экран — от узкого телефона до планшета.
 * Растянутый растр даёт мыло на скруглениях и рвань на тонких линиях
 * орнамента. Вектор тянется без потерь и красится темой.
 *
 * ── Как устроено ──────────────────────────────────────────────────────
 *
 * Три части, потому что тянуться должна только середина:
 *
 *   [медальон]───── двойная линия ─── название ─── линия ─────[медальон]
 *
 * Медальоны — фиксированной ширины, со своей пропорцией: узор в них не
 * искажается. Между ними двойная рамка на всю ширину — это прямые линии,
 * их растяжение незаметно.
 *
 * Узор медальона собран из тех же элементов, что в мусхафе: капля-лепесток
 * в центре, вокруг неё завитки, снаружи зубчики. Рисунок симметричен по
 * вертикали, а правый медальон — зеркало левого.
 */

/** Ширина медальона в пикселях при базовой высоте плашки. */
const MEDALLION_W = 44;

/**
 * Орнаментальный медальон.
 *
 * viewBox 44×34 — пропорция взята с печатной плашки: медальон чуть шире,
 * чем высота рамки, и потому выступает за линии, а не вписан в них.
 */
function Medallion({ height, flip = false }: { height: number; flip?: boolean }) {
  const w = Math.round((MEDALLION_W / 34) * height);
  return (
    <svg
      width={w}
      height={height}
      viewBox="0 0 44 34"
      fill="none"
      aria-hidden="true"
      style={{
        flexShrink: 0,
        transform: flip ? 'scaleX(-1)' : undefined,
        display: 'block',
      }}
    >
      {/* Внешний контур: остриё наружу, как у печати на полях мусхафа. */}
      <path
        d="M43 2.5 H14 C7.5 2.5 2 8 2 17 C2 26 7.5 31.5 14 31.5 H43"
        stroke="var(--gold)"
        strokeWidth="1.1"
        strokeLinecap="round"
      />
      {/* Вторая линия внутри — двойной контур, признак печатной рамки. */}
      <path
        d="M43 5.5 H14.6 C9.2 5.5 5 10 5 17 C5 24 9.2 28.5 14.6 28.5 H43"
        stroke="var(--gold-soft)"
        strokeWidth="0.8"
        strokeLinecap="round"
      />
      {/* Капля-лепесток в сердце медальона. */}
      <path
        d="M14 10.5 C18.5 12.4 20.4 14.6 20.4 17 C20.4 19.4 18.5 21.6 14 23.5 C11.4 22 10.1 19.6 10.1 17 C10.1 14.4 11.4 12 14 10.5 Z"
        stroke="var(--gold)"
        strokeWidth="0.9"
      />
      {/* Точка в центре капли — её ставят и в розетках номеров аятов. */}
      <circle cx="14.6" cy="17" r="1.5" fill="var(--gold)" />
      {/* Завитки над и под каплей. */}
      <path
        d="M20.8 12.2 C24 11 26.6 11.6 27.6 13.6"
        stroke="var(--gold-soft)"
        strokeWidth="0.8"
        strokeLinecap="round"
      />
      <path
        d="M20.8 21.8 C24 23 26.6 22.4 27.6 20.4"
        stroke="var(--gold-soft)"
        strokeWidth="0.8"
        strokeLinecap="round"
      />
      {/* Зубчики по внешнему краю — то же ритмичное «кружево», что на
          скруглении печатной плашки. */}
      <path
        d="M7.4 8.6 L5.6 6.4 M4.4 12.4 L2 11.4 M4.4 21.6 L2 22.6 M7.4 25.4 L5.6 27.6"
        stroke="var(--gold-soft)"
        strokeWidth="0.8"
        strokeLinecap="round"
      />
    </svg>
  );
}

/**
 * Плашка целиком.
 *
 * `height` задаётся вызывающим от кегля страницы: рамка должна расти
 * вместе с текстом, иначе на планшете она окажется марочкой под крупным
 * названием.
 */
export function SurahPlate({
  height,
  children,
}: {
  height: number;
  children: React.ReactNode;
}) {
  return (
    <div
      style={{
        display: 'flex',
        alignItems: 'stretch',
        justifyContent: 'center',
        width: '100%',
        height: `${height}px`,
        // Плашка на странице стоит чуть свободнее строк — в печати вокруг
        // неё тоже оставляют воздух.
        margin: `${Math.round(height * 0.12)}px 0`,
      }}
    >
      <Medallion height={height} />

      {/* Середина: двойная рамка сверху и снизу плюс название по центру.
          Линии — border, а не SVG: так они всегда ровно в один пиксель,
          независимо от того, как растянулась середина. */}
      <div
        style={{
          flex: 1,
          minWidth: 0,
          position: 'relative',
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'center',
          borderTop: '1.1px solid var(--gold)',
          borderBottom: '1.1px solid var(--gold)',
          // Вторая, внутренняя линия — тем же приёмом, тенью внутрь.
          boxShadow:
            'inset 0 3px 0 -2px var(--gold-soft), inset 0 -3px 0 -2px var(--gold-soft)',
          // Подложка теплее страницы: в печати внутри рамки бумага чуть
          // темнее от золотой краски по контуру.
          background: 'color-mix(in srgb, var(--gold) 7%, transparent)',
          overflow: 'hidden',
        }}
      >
        {children}
      </div>

      <Medallion height={height} flip />
    </div>
  );
}
