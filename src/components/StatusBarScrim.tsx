/**
 * StatusBarScrim — подложка под системной строкой (часы, сеть, батарея).
 *
 * ── Что было сломано ──────────────────────────────────────────────────
 *
 * Приложение рисуется во весь экран, под системную строку в том числе.
 * На экранах с закреплённой шапкой (чтение суры, лента азкаров) её
 * фон заодно подкладывался и под часы, и всё читалось.  А на экранах
 * без такой шапки — главный список, азкары, намаз, кибла — под часы
 * уезжал сам контент: названия сур наезжали на время и на значок
 * Wi-Fi.  Видно на скриншоте пользователя: «Аль-Лайл» поверх «11:20».
 *
 * ── Решение ───────────────────────────────────────────────────────────
 *
 * Полоса ровно в высоту безопасной зоны сверху, поверх контента, но
 * ниже панелей настроек.  Не сплошная заливка, а вертикальный градиент
 * от цвета канвы к прозрачности: сплошная полоса на «Мусхафе» легла бы
 * плоским пятном поверх фотографии бумаги и дала бы видимый шов по
 * нижней кромке, а градиент просто растворяется в странице и при этом
 * держит контраст под самими часами.
 *
 * ── Почему здесь больше нет backdrop-filter ───────────────────────────
 *
 * Раньше полоса размывала фон сама (blur 18px).  Но на экранах с
 * ScreenHeader она ложится ровно на верхнюю часть шапки, у которой
 * тоже есть backdrop-filter, — и одна и та же полоса экрана
 * пересчитывалась дважды за кадр прокрутки.  Убрать перекрытие
 * геометрией нельзя: крышка живёт в оболочке экрана (App → Shell), а
 * шапка — внутри контента, в дочернем контексте наложения, поэтому
 * никакой z-index не поднимет её над крышкой.
 *
 * Из двух оставшихся вариантов — «не рисовать крышку под шапкой» и
 * «убрать у крышки размытие» — выбран второй.  Первый требует знать
 * снаружи, есть ли у текущего экрана шапка, то есть тянуть состояние
 * через App и все экраны ради оформления.  Второй ничего не знает про
 * соседей: там, где шапка есть, размывает только она; там, где её нет,
 * градиент и так справляется — под системной строкой нужен контраст, а
 * не стекло.  Заодно из семи мест с backdrop-filter стало шесть.
 *
 * Высота берётся из `env(safe-area-inset-top)`.  Там, где выреза нет
 * и система рисует строку сама (обычные Android-конфигурации), инсет
 * равен нулю, полоса схлопывается и ничего не делает.
 *
 * ── Почему без color-mix в инлайне ────────────────────────────────────
 *
 * Раньше градиент строился через `color-mix(in srgb, var(--bg) …)`.
 * Минимальная iOS — 15.0, а `color-mix` работает с Safari 16.4. Инлайн
 * стиль минификатор не полифиллит (в отличие от правил в CSS), поэтому
 * на iOS 15–16.1 весь `background` был невалиден и подложки не было —
 * часы и Wi‑Fi смешивались с контентом списка сур. Сейчас: плотный
 * `var(--bg)` и маска, уходящая в прозрачность.
 *
 * Почему поверх, а не «отступ у контента»: отступ убрал бы наезд, но
 * тогда при прокрутке текст всё равно проходил бы под часами — он же
 * скроллится. Нужна именно крышка.
 */

export function StatusBarScrim() {
  return (
    <div
      aria-hidden="true"
      style={{
        position: 'fixed',
        top: 0,
        left: 0,
        right: 0,
        height: 'env(safe-area-inset-top, 0px)',
        zIndex: 30,
        pointerEvents: 'none',
        background: 'var(--bg)',
        opacity: 0.92,
        // Кривая та же, что была у прежнего градиента: 92 % у верхней
        // кромки, ~74 % на 58 % высоты, ноль внизу. Ровная плотность до
        // 58 % давала плоское пятно поверх фотографии бумаги на теме
        // «мусхаф» и поверх звёздного слоя на «авроре».
        WebkitMaskImage:
          'linear-gradient(to bottom, #000 0%, rgba(0,0,0,0.8) 58%, transparent 100%)',
        maskImage:
          'linear-gradient(to bottom, #000 0%, rgba(0,0,0,0.8) 58%, transparent 100%)',
      }}
    />
  );
}
