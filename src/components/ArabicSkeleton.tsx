/**
 * ArabicSkeleton — то, что стоит на месте арабского текста, пока грузится
 * шрифт мусхафа.
 *
 * ── Почему не кубики ──────────────────────────────────────────────────
 *
 * Слова мусхафа — готовые глифы в приватной области Unicode (U+F100…).
 * Ни один системный шрифт их не знает, поэтому запасного варианта нет:
 * пока файл не пришёл, браузер рисует ряды пустых квадратов.  На месте
 * аята это выглядит как испорченный текст, а не как загрузка.
 *
 * Скелет говорит честно: строки ещё едут.  Форму берём у самого текста —
 * строки разной длины, выключка вправо, последняя строка короче, — чтобы
 * подмена на настоящий аят не дёргала вёрстку.
 *
 * ── Почему полоски, а не «крутилка» ───────────────────────────────────
 *
 * Спиннер на месте текста сообщает «что-то происходит», но не сколько
 * места это займёт: страница прыгает, когда текст приходит.  Полоски
 * держат высоту строки и её ритм, поэтому появление аята выглядит как
 * проявление, а не как перестройка экрана.
 *
 * Движение — мягкий пульс, не «бегущий блик»: экран с аятом не место для
 * аттракциона.  При `prefers-reduced-motion` пульс выключается (правило
 * в src/index.css), полоски остаются.
 */

type Props = {
  /** Сколько строк занять — обычно длина аята в строках мусхафа. */
  lines?: number;
  /** Кегль арабского в px: скелет держит тот же ритм строки. */
  fontSize: number;
  /** Выравнивание: в ленте аятов текст идёт вправо, на странице — по ширине. */
  align?: 'right' | 'stretch';
};

/**
 * Доли ширины строк.  Не случайные: у аята первые строки почти во всю
 * ширину, последняя оборвана — так это и читается глазом.  Случайные
 * значения при каждом рендере дёргались бы на любом обновлении.
 */
const WIDTHS = [0.97, 0.93, 0.99, 0.88, 0.95, 0.91, 0.98, 0.72];

export function ArabicSkeleton({ lines = 2, fontSize, align = 'right' }: Props) {
  const count = Math.max(1, Math.min(lines, 12));
  const lineHeight = fontSize * 1.85;   // как в QcfAyahLine
  const barHeight = Math.round(fontSize * 0.42);

  return (
    <div
      aria-hidden="true"
      style={{
        display: 'flex',
        flexDirection: 'column',
        gap: `${Math.round(lineHeight - barHeight)}px`,
        alignItems: align === 'right' ? 'flex-end' : 'stretch',
        padding: '4px 2px',
      }}
    >
      {Array.from({ length: count }, (_, i) => {
        const isLast = i === count - 1;
        const width = align === 'stretch' && !isLast
          ? '100%'
          : `${Math.round((isLast ? 0.6 : WIDTHS[i % WIDTHS.length]) * 100)}%`;
        return (
          <div
            key={i}
            className="arabic-skeleton-bar"
            style={{
              width,
              height: `${barHeight}px`,
              borderRadius: `${Math.round(barHeight / 2)}px`,
              // Тон от чернил темы, а не фиксированный серый: на бумаге
              // мусхафа и в тёмной теме нужны разные полоски.
              background: 'color-mix(in srgb, var(--ink) 9%, transparent)',
              // Задержка волной — читается как «строки едут одна за другой».
              animationDelay: `${i * 90}ms`,
            }}
          />
        );
      })}
    </div>
  );
}
