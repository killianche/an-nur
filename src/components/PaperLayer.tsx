/**
 * PaperLayer — фон темы «Мусхаф»: настоящая фотография бумаги.
 *
 * Раньше страница была плоской заливкой #f5efe1 с нарисованной
 * виньеткой.  Издали похоже на бумагу, вблизи — заливка: у настоящего
 * листа есть волокно, и глаз это читает даже там, где не может назвать.
 *
 * ── Почему тон запечён в файл, а не наложен в CSS ─────────────────────
 *
 * Исходная фотография почти белая. Чтобы получить бежевую бумагу с
 * живым зерном, её нужно УМНОЖИТЬ на тон: тогда волокна темнеют
 * пропорционально, как на настоящем листе.  Полупрозрачная бежевая
 * плёнка поверх дала бы не то — она гасит контраст зерна почти в ноль
 * (перепад ±8 уровней превращается в ±2).
 *
 * Умножать можно и в браузере (`mix-blend-mode: multiply`), но этот
 * приём уже однажды стоил нам плавности прокрутки в «Авроре»: WebKit
 * пересчитывает смешивание для `position: fixed` на каждом кадре
 * скролла.  Поэтому умножение сделано один раз при подготовке ассета
 * (см. историю коммита), а сюда приезжает готовая картинка — обычный
 * слой без смешивания, ноль работы на кадр.
 *
 * Цена решения: тон бумаги живёт в файле, а не в переменной. Захочется
 * другой оттенок — пересобрать webp из paper-texture.jpg. Тон файла и
 * `--canvas` в index.css обязаны совпадать: под фактурой лежит именно
 * canvas, и на широком экране, где картинка не покрывает всё поле, шва
 * быть не должно.
 *
 * Виньетка осталась в CSS: она зависит от размеров экрана, и рисовать
 * её в файле пришлось бы под каждое соотношение сторон.
 */

export function PaperLayer() {
  return (
    <div
      aria-hidden="true"
      style={{
        position: 'fixed',
        inset: 0,
        zIndex: 0,
        pointerEvents: 'none',
        backgroundColor: 'var(--bg)',
        backgroundImage: 'url(/textures/paper-mushaf.webp)',
        backgroundSize: 'cover',
        backgroundPosition: 'center',
        backgroundRepeat: 'no-repeat',
        // Тот же приём изоляции, что у CosmicLayer: слой растеризуется
        // один раз и дальше просто лежит под контентом.
        contain: 'strict',
        transform: 'translateZ(0)',
        backfaceVisibility: 'hidden',
      }}
    >
      {/* Виньетка — у сгиба и обреза бумага всегда чуть темнее.
          Без неё лист выглядит отсканированным, а не раскрытым. */}
      <div
        style={{
          position: 'absolute',
          inset: 0,
          background: `
            radial-gradient(140vw 100vh at 50% 50%,
              transparent 55%,
              rgba(120, 96, 58, 0.13) 100%),
            linear-gradient(to right,
              rgba(120, 96, 58, 0.09) 0%,
              transparent 7%,
              transparent 93%,
              rgba(120, 96, 58, 0.09) 100%)
          `,
        }}
      />
    </div>
  );
}
