/**
 * PaperLayer — виньетка темы «Мусхаф».
 *
 * Сама бумага сюда больше не входит: её фактура лежит фоном на <body>
 * (см. `[data-theme="mushaf"] body` в index.css) и едет вместе с
 * текстом.  Здесь остался только неподвижный слой тени по краям.
 *
 * ── Почему бумага скроллится, а виньетка нет ──────────────────────────
 *
 * Пока фактура была неподвижной, текст ехал ПОВЕРХ неё — читалось как
 * стекло, за которым лежит лист, а не как сам лист.  Владелец это
 * заметил и попросил, чтобы бумага поднималась вместе с прокруткой.
 * Фон на <body> с `repeat-y` даёт ровно это, без JS и без слоя.
 *
 * Виньетка же изображает не бумагу, а свет: затемнение у кромок
 * ЭКРАНА.  Поедет вместе с текстом — превратится в тёмные полосы,
 * повторяющиеся по всей странице.  Поэтому осталась `fixed`.
 *
 * ── Про бесшовность ───────────────────────────────────────────────────
 *
 * `repeat-y` показал бы стык на каждой высоте плитки, поэтому файл
 * собран зеркальным: нижняя половина — отражение верхней, и последняя
 * строка пикселей совпадает с первой (проверено: расхождение 0).
 * Зеркало, а не растушёвка шва: зерно бумаги высокочастотное и
 * однородное, симметрия на нём не читается, а растушёвка оставила бы
 * размытую полосу, которую как раз видно.
 */

export function PaperLayer() {
  return (
    <div
      aria-hidden="true"
      style={{
        position: 'fixed',
        inset: 0,
        zIndex: 0,
        pointerEvents: 'none',
        // Тень у сгиба и обреза.  Без неё лист выглядит отсканированным,
        // а не раскрытым.  Держим слабой: на белой бумаге тёмные края
        // быстро начинают читаться как грязь.
        background: `
          radial-gradient(140vw 100vh at 50% 50%,
            transparent 55%,
            rgba(60, 60, 58, 0.06) 100%),
          linear-gradient(to right,
            rgba(60, 60, 58, 0.045) 0%,
            transparent 7%,
            transparent 93%,
            rgba(60, 60, 58, 0.045) 100%)
        `,
        contain: 'strict',
        transform: 'translateZ(0)',
        backfaceVisibility: 'hidden',
      }}
    />
  );
}
