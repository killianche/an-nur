/**
 * PaperLayer — фон темы «Мусхаф»: настоящая фотография бумаги.
 *
 * Раньше страница была плоской заливкой #f5efe1 с нарисованной
 * виньеткой.  Издали похоже на бумагу, вблизи — заливка: у настоящего
 * листа есть волокно, и глаз это читает даже там, где не может назвать.
 *
 * ── Почему тон запечён в файл, а не наложен в CSS ─────────────────────
 *
 * Фотография почти белая — ровно то, что нужно: от темы требуется
 * фактура, а не оттенок.  Тонировать её ничем не надо, достаточно
 * поднять контраст при подготовке файла, иначе на экране волокно
 * пропадает.
 *
 * Была промежуточная версия с бежевым тоном, запечённым в файл
 * умножением. Снята по решению владельца: «нужна текстура, но белая».
 * Если оттенок когда-нибудь вернётся — умножать надо именно при
 * подготовке ассета, а не в браузере: `mix-blend-mode` на
 * `position: fixed` заставляет WebKit пересчитывать смешивание на
 * каждом кадре скролла, это уже однажды стоило нам плавности в
 * «Авроре».
 *
 * Виньетка осталась в CSS: она зависит от размеров экрана, и рисовать
 * её в файле пришлось бы под каждое соотношение сторон.
 */

export function PaperLayer() {
  return (
    <div
      aria-hidden="true"
      style={{
        position: 'fixed',
        inset: 0,
        zIndex: 0,
        pointerEvents: 'none',
        backgroundColor: 'var(--bg)',
        backgroundImage: 'url(/textures/paper-mushaf.webp)',
        backgroundSize: 'cover',
        backgroundPosition: 'center',
        backgroundRepeat: 'no-repeat',
        // Тот же приём изоляции, что у CosmicLayer: слой растеризуется
        // один раз и дальше просто лежит под контентом.
        contain: 'strict',
        transform: 'translateZ(0)',
        backfaceVisibility: 'hidden',
      }}
    >
      {/* Виньетка — у сгиба и обреза бумага всегда чуть темнее.
          Без неё лист выглядит отсканированным, а не раскрытым. */}
      <div
        style={{
          position: 'absolute',
          inset: 0,
          background: `
            radial-gradient(140vw 100vh at 50% 50%,
              transparent 55%,
              rgba(60, 60, 58, 0.06) 100%),
            linear-gradient(to right,
              rgba(60, 60, 58, 0.045) 0%,
              transparent 7%,
              transparent 93%,
              rgba(60, 60, 58, 0.045) 100%)
          `,
        }}
      />
    </div>
  );
}
