/**
 * MushafFrame — орнаментальная рамка печатной страницы мусхафа.
 *
 * ── Почему SVG в border-image, а не картинка ──────────────────────────
 *
 * Растр пришлось бы держать в нескольких плотностях, и на планшете он всё
 * равно мылился бы: рамка тянется на всю высоту экрана. SVG в
 * `border-image` тянется без потерь и весит сотни байт вместо сотен
 * килобайт. Пакет приложения и так на пределе (см. STATUS.md, § размеры).
 *
 * ── Почему орнамент нарисован, а не взят готовый ──────────────────────
 *
 * Готовые исламские бордюры почти всегда приходят без прослеживаемой
 * лицензии. Для проекта, где даже шрифты сопровождаются документом об
 * основании использования (`docs/licenses/ARABIC_QURAN_FONTS.md`), тащить
 * орнамент с файлопомойки нельзя. Здесь — простой геометрический мотив,
 * построенный из повторяющегося ромба с внутренней засечкой: он читается
 * как печатная рамка, но не воспроизводит чужую работу.
 *
 * ── Что рамка НЕ делает ───────────────────────────────────────────────
 *
 * Не несёт содержания. Внутри неё ничего не меняется: сакральный текст
 * приходит из данных мусхафа посимвольно, как и в простом оформлении.
 * Рамка не участвует в подборе кегля — она рисуется отдельным слоем
 * поверх, `pointer-events: none`, и не влияет на геометрию страницы.
 * Это важно: любое изменение размеров запускает пересчёт кегля QCF.
 */

/** Толщина рамки в пикселях. Тоньше — теряется рисунок, толще — съедает страницу. */
export const FRAME_WIDTH = 10;

/**
 * Повторяющееся звено бордюра.
 *
 * Мотив: ряд ромбов с точкой в центре, между ними — вертикальные засечки.
 * Рисуется в координатах 0…20 и повторяется вдоль каждой стороны; углы
 * закрываются тем же мотивом за счёт `border-image-repeat: round`.
 */
function borderImage(ink: string, accent: string): string {
  const svg = `
<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 20 20">
  <rect x="0" y="0" width="20" height="20" fill="none"/>
  <rect x="0.9" y="0.9" width="18.2" height="18.2" fill="none"
        stroke="${ink}" stroke-width="1.1"/>
  <rect x="4.2" y="4.2" width="11.6" height="11.6" fill="none"
        stroke="${accent}" stroke-width="0.8"/>
  <path d="M10 2.2 L12.6 10 L10 17.8 L7.4 10 Z" fill="${accent}" opacity="0.85"/>
  <circle cx="10" cy="10" r="1.5" fill="${ink}"/>
</svg>`.trim();
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}

/**
 * Рамка вокруг текстового блока страницы.
 *
 * Цвета берутся из токенов темы, а не задаются жёстко: печатное
 * оформление обязано оставаться читаемым во всех пяти темах, включая
 * тёмную. В печатном режиме страница сама кремовая, но пользователь
 * может держать тёмную тему для остального приложения.
 */
export function MushafFrame() {
  return (
    <div
      aria-hidden="true"
      style={{
        position: 'absolute',
        inset: 0,
        pointerEvents: 'none',
        borderStyle: 'solid',
        borderWidth: `${FRAME_WIDTH}px`,
        borderColor: 'transparent',
        borderImageSource: borderImage('var(--mushaf-frame-ink)', 'var(--mushaf-frame-accent)'),
        borderImageSlice: 10,
        borderImageWidth: `${FRAME_WIDTH}px`,
        borderImageRepeat: 'round',
        // Тонкая внутренняя линейка — как в печатном издании, где текст
        // отделён от орнамента волосяным штрихом.
        boxShadow: 'inset 0 0 0 1px var(--mushaf-frame-rule)',
      }}
    />
  );
}
