/**
 * Зона касания 44×44 поверх кнопки, которая по рисунку меньше.
 *
 * Apple просит минимум 44×44 pt на любой управляющий элемент, но часть
 * кнопок в приложении по рисунку мельче: круглые «скрыть», «плюс», «минус»,
 * «очистить поле», колокольчик намаза. Увеличивать сам кружок нельзя — он
 * встроен в ритм строки, — поэтому палец получает положенный минимум
 * отдельным прозрачным слоем, а глиф остаётся своего размера.
 *
 * Тот же приём, что у `.dock-btn::after` в index.css. Здесь он обычным
 * элементом, а не псевдоэлементом: вёрстка экранов живёт в инлайн-стилях,
 * а из них псевдоэлемент не задать.
 *
 * Слой прозрачен и выведен из потока, поэтому не сдвигает глиф; нажатие по
 * нему всплывает в саму кнопку. `minWidth`/`minHeight` в 100% нужны, чтобы
 * у кнопки ШИРЕ 44 зона не сузилась до 44.
 *
 * Кнопке-родителю обязателен `position: relative` — иначе зона отсчитается
 * от ближайшего позиционированного предка и уедет.
 *
 * Проверять расстановку: соседние зоны не должны накладываться. Если между
 * двумя мелкими кнопками зазор меньше `--space-cozy`, их расширенные зоны
 * пересекутся и край одной начнёт отдавать нажатие другой.
 */
export function HitArea() {
  return (
    <span
      aria-hidden
      style={{
        position: 'absolute',
        top: '50%',
        left: '50%',
        width: 'var(--hit-min)',
        height: 'var(--hit-min)',
        minWidth: '100%',
        minHeight: '100%',
        transform: 'translate(-50%, -50%)',
      }}
    />
  );
}
